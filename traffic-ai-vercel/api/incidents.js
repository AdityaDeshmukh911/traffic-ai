// In-memory incident store per serverless instance (frontend also syncs state)
const CAPACITY_IMPACT = {
  Accident: 0.45,
  Breakdown: 0.65,
  Roadworks: 0.60,
  Closure: 0.15,
  'Congestion Alert': 0.85
};

let incidentsStore = [
  {
    id: 'INC-101',
    junction: 'B2',
    type: 'Roadworks',
    severity: 'Medium',
    status: 'Active',
    capacityFactor: 0.60,
    notes: 'Utility trenching on eastbound lane',
    createdAt: new Date(Date.now() - 180000).toISOString(),
    autoGenerated: false
  }
];

function parseBody(req) {
  let body = req.body || {};
  if (typeof body === 'string') {
    try { body = JSON.parse(body); } catch { body = {}; }
  }
  return body;
}

module.exports = function handler(req, res) {
  res.setHeader('Content-Type', 'application/json');

  if (req.method === 'GET') {
    res.statusCode = 200;
    res.end(JSON.stringify({ incidents: incidentsStore }));
    return;
  }

  if (req.method === 'POST') {
    const body = parseBody(req);
    const junction = body.junction || 'B2';
    const type = body.type || 'Accident';
    const severity = body.severity || 'Medium';
    const notes = (body.notes || '').toString().trim().slice(0, 200) || `${type} reported at ${junction}`;

    if (body.autoGenerated) {
      const duplicate = incidentsStore.find(
        (i) => i.junction === junction && i.status !== 'Resolved' && i.type === 'Congestion Alert'
      );
      if (duplicate) {
        res.statusCode = 200;
        res.end(JSON.stringify({ incident: duplicate, deduplicated: true }));
        return;
      }
    }

    const baseFactor = CAPACITY_IMPACT[type] !== undefined ? CAPACITY_IMPACT[type] : 0.65;
    const sevAdj = severity === 'High' ? -0.15 : severity === 'Low' ? 0.10 : 0;
    const capacityFactor = Math.max(0.15, Math.min(0.90, Number((baseFactor + sevAdj).toFixed(2))));

    const newInc = {
      id: `INC-${Math.floor(100 + Math.random() * 900)}`,
      junction,
      type,
      severity,
      status: 'Active',
      capacityFactor,
      notes,
      createdAt: new Date().toISOString(),
      autoGenerated: Boolean(body.autoGenerated)
    };
    incidentsStore.unshift(newInc);
    res.statusCode = 201;
    res.end(JSON.stringify({ incident: newInc }));
    return;
  }

  if (req.method === 'PATCH') {
    const body = parseBody(req);
    const target = incidentsStore.find((i) => i.id === body.id);
    if (!target) {
      res.statusCode = 404;
      res.end(JSON.stringify({ error: 'Incident not found' }));
      return;
    }

    if (body.action === 'resolve') {
      target.status = 'Resolved';
    } else if (body.action === 'reopen') {
      target.status = 'Active';
    } else if (body.action === 'advance') {
      target.status = target.status === 'Active' ? 'Responding' : 'Resolved';
    }
    res.statusCode = 200;
    res.end(JSON.stringify({ incident: target }));
    return;
  }

  res.statusCode = 405;
  res.end(JSON.stringify({ error: 'Method not allowed' }));
};
